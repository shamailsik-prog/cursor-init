#!/usr/bin/env python3
"""Generate data/confusables-ascii-subset.json from the Unicode UTS #39 confusables.txt.

Usage: python3 scripts/generate-confusables-subset.py <path/to/confusables.txt>

Review round 3 (draft charset refusal layer): the draft gate refuses a Latin-letter token
whose confusable skeleton differs from its folded form. We ship only the subset needed for
that: every *non-ASCII* single code point whose prototype is a short run of ASCII letters or
digits (A-Z, a-z, 0-9 — which covers every letter of every reporter token). ASCII sources
are excluded on purpose ("l"->"I", "0"->"O", "m"->"rn" would refuse ordinary text).
The data is read from a local file; nothing is fetched at runtime.
"""
import json
import re
import sys

src = sys.argv[1]
header_date = ""
entries = {}
with open(src, encoding="utf-8") as fh:
    for line in fh:
        if line.startswith("# Date:"):
            header_date = line[len("# Date:"):].strip()
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split(";")]
        if len(parts) < 2:
            continue
        source = [int(x, 16) for x in parts[0].split()]
        target = "".join(chr(int(x, 16)) for x in parts[1].split())
        if len(source) != 1 or source[0] < 0x80:
            continue
        if not re.fullmatch(r"[A-Za-z0-9]{1,2}", target):
            continue
        entries["%04X" % source[0]] = target

out = {
    "source": "Unicode UTS #39 confusables.txt",
    "sourceDate": header_date,
    "note": "non-ASCII single code points whose prototype is 1-2 ASCII letters/digits; generated by scripts/generate-confusables-subset.py",
    "map": dict(sorted(entries.items(), key=lambda kv: int(kv[0], 16))),
}
with open("data/confusables-ascii-subset.json", "w", encoding="utf-8") as fh:
    json.dump(out, fh, ensure_ascii=True, indent=0, sort_keys=False)
    fh.write("\n")
print(len(entries), "entries")
