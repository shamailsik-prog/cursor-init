#!/usr/bin/env python3
"""Unit tests for ci_gates/check_corpus_runtime_pins.py."""

from __future__ import annotations

import json
import os
import tempfile
import unittest
from pathlib import Path

from check_corpus_runtime_pins import run

_HASH = "a" * 64


def _shipped_tree_root() -> Path:
    for key in ("GITHUB_WORKSPACE", "SIKANDER_GATE_TOOL_ROOT", "WORKSPACE_ROOT"):
        raw = os.environ.get(key)
        if raw:
            return Path(raw).resolve()
    return Path(__file__).resolve().parents[1]


def _write_probe_tree(root: Path, *, req_txt: str, req_test: str, py_digest: str) -> None:
    corpus = root / "corpus_service"
    corpus.mkdir(parents=True)
    (corpus / "requirements.in").write_text("fastapi\n", encoding="utf-8")
    (corpus / "requirements.txt").write_text(req_txt, encoding="utf-8")
    (corpus / "requirements-test.txt").write_text(req_test, encoding="utf-8")
    (corpus / "Dockerfile").write_text(
        f"FROM python:3.12-slim@sha256:{py_digest}\n"
        "RUN pip install --require-hashes -r requirements.txt\n",
        encoding="utf-8",
    )
    pg_d, redis_d, py_d = "c" * 64, "d" * 64, py_digest
    (corpus / "docker-compose.yml").write_text(
        f"services:\n  postgres:\n    image: pgvector/pgvector:pg16@sha256:{pg_d}\n"
        f"  redis:\n    image: redis:7-alpine@sha256:{redis_d}\n",
        encoding="utf-8",
    )
    lock = {
        "images": {
            "python_base": {
                "reference": "docker.io/library/python:3.12-slim",
                "digest": f"sha256:{py_d}",
            },
            "pgvector_pg16": {"reference": "x", "digest": f"sha256:{pg_d}"},
            "redis_7_alpine": {"reference": "x", "digest": f"sha256:{redis_d}"},
        }
    }
    (corpus / "runtime-images.lock.json").write_text(json.dumps(lock), encoding="utf-8")
    (corpus / "runtime-sbom.json").write_text(
        json.dumps(
            {
                "parsers_and_media": {},
                "data_stack": {},
                "base_image": f"docker.io/library/python:3.12-slim@sha256:{py_d}",
            }
        ),
        encoding="utf-8",
    )
    e2e = corpus / "tests" / "e2e"
    e2e.mkdir(parents=True)
    pg_ref = f"pgvector/pgvector:pg16@sha256:{pg_d}"
    redis_ref = f"redis:7-alpine@sha256:{redis_d}"
    for name in ("store_security_e2e.sh", "upgrade_e2e.sh"):
        (e2e / name).write_text(
            f'PG_IMAGE="{pg_ref}"\nREDIS_IMAGE="{redis_ref}"\n',
            encoding="utf-8",
        )


def _valid_req_block(name: str, ver: str) -> str:
    return (
        f"# This file is autogenerated by pip-compile\n"
        f"{name}=={ver} \\\n"
        f"    --hash=sha256:{_HASH}\n"
    )


class CorpusRuntimePinsGuardTest(unittest.TestCase):
    def test_shipped_repo_passes(self):
        root = _shipped_tree_root()
        self.assertEqual(run(root), [])

    def test_unpinned_requirements_fail(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _write_probe_tree(
                root,
                req_txt="# This file is autogenerated by pip-compile\nfastapi\n",
                req_test=_valid_req_block("pytest", "1.0.0"),
                py_digest="b" * 64,
            )
            problems = run(root)
            self.assertTrue(problems, problems)

    def test_fastapi_ge_operator_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _write_probe_tree(
                root,
                req_txt="# This file is autogenerated by pip-compile\nfastapi>=0.100.0\n",
                req_test=_valid_req_block("pytest", "1.0.0"),
                py_digest="b" * 64,
            )
            self.assertTrue(run(root))

    def test_unpinned_requests_line_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _write_probe_tree(
                root,
                req_txt="# This file is autogenerated by pip-compile\nrequests\n",
                req_test=_valid_req_block("pytest", "1.0.0"),
                py_digest="b" * 64,
            )
            self.assertTrue(run(root))

    def test_invalid_python_digest_length_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            short = "deadbeef" * 7 + "de"  # 58 chars — invalid
            _write_probe_tree(
                root,
                req_txt=_valid_req_block("fastapi", "1.0.0"),
                req_test=_valid_req_block("pytest", "1.0.0"),
                py_digest=short,
            )
            problems = run(root)
            self.assertTrue(any("digest must match" in p for p in problems), problems)


if __name__ == "__main__":
    unittest.main()
