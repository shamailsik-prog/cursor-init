#!/usr/bin/env python3
"""Unit tests for ci_gates/check_corpus_runtime_pins.py."""

from __future__ import annotations

import json
import os
import tempfile
import unittest
from pathlib import Path

from check_corpus_runtime_pins import run


def _shipped_tree_root() -> Path:
    for key in ("GITHUB_WORKSPACE", "SIKANDER_GATE_TOOL_ROOT", "WORKSPACE_ROOT"):
        raw = os.environ.get(key)
        if raw:
            return Path(raw).resolve()
    return Path(__file__).resolve().parents[1]


class CorpusRuntimePinsGuardTest(unittest.TestCase):
    def test_shipped_repo_passes(self):
        root = _shipped_tree_root()
        self.assertEqual(run(root), [])

    def test_unpinned_requirements_fail(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            corpus = root / "corpus_service"
            corpus.mkdir()
            (corpus / "requirements.in").write_text("fastapi\n", encoding="utf-8")
            (corpus / "requirements.txt").write_text(
                "# This file is autogenerated by pip-compile\nfastapi\n",
                encoding="utf-8",
            )
            (corpus / "requirements-test.txt").write_text(
                "# This file is autogenerated by pip-compile\nfastapi\npytest==1.0.0 \\\n"
                "    --hash=sha256:" + "a" * 64 + "\n",
                encoding="utf-8",
            )
            (corpus / "Dockerfile").write_text(
                "FROM python:3.12-slim@sha256:" + "b" * 64 + "\n"
                "RUN pip install --require-hashes -r requirements.txt\n",
                encoding="utf-8",
            )
            (corpus / "docker-compose.yml").write_text(
                "services:\n  postgres:\n    image: pgvector/pgvector:pg16@sha256:" + "c" * 64 + "\n"
                "  redis:\n    image: redis:7-alpine@sha256:" + "d" * 64 + "\n",
                encoding="utf-8",
            )
            lock = {
                "images": {
                    "python_base": {"reference": "x", "digest": "sha256:" + "b" * 64},
                    "pgvector_pg16": {"reference": "x", "digest": "sha256:" + "c" * 64},
                    "redis_7_alpine": {"reference": "x", "digest": "sha256:" + "d" * 64},
                }
            }
            (corpus / "runtime-images.lock.json").write_text(json.dumps(lock), encoding="utf-8")
            (corpus / "runtime-sbom.json").write_text(
                json.dumps({"parsers_and_media": {}, "data_stack": {}}), encoding="utf-8"
            )
            e2e = corpus / "tests" / "e2e"
            e2e.mkdir(parents=True)
            pg_ref = f"pgvector/pgvector:pg16@sha256:{('c' * 64)}"
            redis_ref = f"redis:7-alpine@sha256:{('d' * 64)}"
            for name in ("store_security_e2e.sh", "upgrade_e2e.sh"):
                (e2e / name).write_text(
                    f'PG_IMAGE="{pg_ref}"\nREDIS_IMAGE="{redis_ref}"\n',
                    encoding="utf-8",
                )
            problems = run(root)
            self.assertTrue(problems, problems)


if __name__ == "__main__":
    unittest.main()
