#!/usr/bin/env python3
"""Audit F46: corpus runtime pins — hashed Python lockfiles and immutable container images.

Fails when:
  - corpus_service/requirements.txt is not a pip-compile lock with per-package hashes
  - corpus_service/requirements-test.txt does not pin the same versions as requirements.txt for every
    shared distribution (test set is a superset that includes the production lock)
  - corpus_service/Dockerfile does not install with --require-hashes or uses a mutable base image
  - corpus_service/docker-compose.yml store/helper images are not pinned to runtime-images.lock.json
  - corpus_service/runtime-sbom.json drifts from requirements.txt for tracked parser/stack packages

Usage: python3 ci_gates/check_corpus_runtime_pins.py [--root DIR]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

CORPUS = Path("corpus_service")
REQ = CORPUS / "requirements.txt"
REQ_TEST = CORPUS / "requirements-test.txt"
REQ_IN = CORPUS / "requirements.in"
DOCKERFILE = CORPUS / "Dockerfile"
COMPOSE = CORPUS / "docker-compose.yml"
IMAGE_LOCK = CORPUS / "runtime-images.lock.json"
SBOM = CORPUS / "runtime-sbom.json"

COMPILE_HEADER = re.compile(r"^\s*#\s+This file is autogenerated by pip-compile\b", re.I | re.M)
ENTRY_START = re.compile(
    r"^([A-Za-z0-9][A-Za-z0-9_.-]*)(?:\[[^\]]+\])?==([^\s\\#]+)",
    re.M,
)


def _normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_locked_requirements(text: str) -> tuple[dict[str, str], list[str]]:
    """Return (name->version, problems). Every pinned entry must include at least one sha256 hash."""
    versions: dict[str, str] = {}
    problems: list[str] = []
    matches = list(ENTRY_START.finditer(text))
    if not matches:
        return versions, problems
    for i, m in enumerate(matches):
        start = m.start()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        block = text[start:end]
        name, ver = _normalize(m.group(1)), m.group(2)
        if "--hash=sha256:" not in block:
            problems.append(f"{name}=={ver} has no --hash=sha256 lines")
        elif name in versions and versions[name] != ver:
            problems.append(f"{name} pinned twice with different versions ({versions[name]!r} vs {ver!r})")
        else:
            versions[name] = ver
    return versions, problems


def check_requirements_txt(root: Path) -> list[str]:
    path = root / REQ
    text = path.read_text(encoding="utf-8")
    problems: list[str] = []
    if not COMPILE_HEADER.search(text):
        problems.append(f"{REQ}: missing pip-compile autogenerated header (run scripts/compile_requirements.sh)")
    if not (root / REQ_IN).is_file():
        problems.append(f"{REQ_IN}: missing (source manifest for pip-compile)")
    versions, inner = parse_locked_requirements(text)
    problems.extend(f"{REQ}: {p}" for p in inner)
    if not versions:
        problems.append(f"{REQ}: no pinned packages found")
    return problems


def check_test_superset(root: Path) -> list[str]:
    prod, p1 = parse_locked_requirements((root / REQ).read_text(encoding="utf-8"))
    test, p2 = parse_locked_requirements((root / REQ_TEST).read_text(encoding="utf-8"))
    problems = [f"{REQ_TEST}: {p}" for p in p2]
    test_text = (root / REQ_TEST).read_text(encoding="utf-8")
    if not COMPILE_HEADER.search(test_text):
        problems.append(f"{REQ_TEST}: missing pip-compile autogenerated header")
    for name, ver in prod.items():
        if test.get(name) != ver:
            problems.append(
                f"{REQ_TEST}: {name} must match {REQ} ({ver!r}); got {test.get(name)!r}"
            )
    if "pytest" not in test:
        problems.append(f"{REQ_TEST}: pytest must be in the test lockfile")
    return problems


def check_dockerfile(root: Path) -> list[str]:
    text = (root / DOCKERFILE).read_text(encoding="utf-8")
    problems: list[str] = []
    lock = json.loads((root / IMAGE_LOCK).read_text(encoding="utf-8"))
    digest = lock["images"]["python_base"]["digest"]
    if digest not in text:
        problems.append(f"{DOCKERFILE}: base image must include digest {digest}")
    if "--require-hashes" not in text:
        problems.append(f"{DOCKERFILE}: pip install must pass --require-hashes")
    if "pip install" in text and "-r requirements.txt" not in text:
        problems.append(f"{DOCKERFILE}: must install from requirements.txt")
    return problems


def _image_refs_in_compose(text: str) -> set[str]:
    refs: set[str] = set()
    for m in re.finditer(r"^\s*image:\s*(\S+)", text, re.M):
        refs.add(m.group(1).strip("\"'"))
    return refs


def check_compose_images(root: Path) -> list[str]:
    lock = json.loads((root / IMAGE_LOCK).read_text(encoding="utf-8"))
    pg_digest = lock["images"]["pgvector_pg16"]["digest"]
    redis_digest = lock["images"]["redis_7_alpine"]["digest"]
    text = (root / COMPOSE).read_text(encoding="utf-8")
    problems: list[str] = []
    refs = _image_refs_in_compose(text)
    pg_hits = [r for r in refs if r.startswith("pgvector/pgvector:pg16@")]
    redis_hits = [r for r in refs if r.startswith("redis:7-alpine@")]
    if not pg_hits or pg_digest not in pg_hits[0]:
        problems.append(f"{COMPOSE}: pgvector/pgvector:pg16 must be pinned to {pg_digest}")
    if not redis_hits or redis_digest not in redis_hits[0]:
        problems.append(f"{COMPOSE}: redis:7-alpine must be pinned to {redis_digest}")
    mutable_pg = [r for r in refs if r == "pgvector/pgvector:pg16"]
    mutable_redis = [r for r in refs if r == "redis:7-alpine"]
    if mutable_pg:
        problems.append(f"{COMPOSE}: mutable tag pgvector/pgvector:pg16 still present")
    if mutable_redis:
        problems.append(f"{COMPOSE}: mutable tag redis:7-alpine still present")
    return problems


def check_sbom(root: Path) -> list[str]:
    pins, _ = parse_locked_requirements((root / REQ).read_text(encoding="utf-8"))
    doc = json.loads((root / SBOM).read_text(encoding="utf-8"))
    problems: list[str] = []
    for section in ("parsers_and_media", "data_stack"):
        for name, ver in doc.get(section, {}).items():
            key = _normalize(name)
            if pins.get(key) != ver:
                problems.append(f"{SBOM}: {section}.{name} is {ver!r} but {REQ} has {pins.get(key)!r}")
    return problems


def run(root: Path) -> list[str]:
    problems: list[str] = []
    for path in (REQ, REQ_TEST, REQ_IN, DOCKERFILE, COMPOSE, IMAGE_LOCK, SBOM):
        if not (root / path).is_file():
            problems.append(f"missing {path}")
    if problems:
        return problems
    problems.extend(check_requirements_txt(root))
    problems.extend(check_test_superset(root))
    problems.extend(check_dockerfile(root))
    problems.extend(check_compose_images(root))
    problems.extend(check_sbom(root))
    return problems


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path.cwd())
    args = parser.parse_args()
    problems = run(args.root.resolve())
    if problems:
        for p in problems:
            print(f"FAIL {p}")
        return 1
    print("PASS corpus runtime pins (F46)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
