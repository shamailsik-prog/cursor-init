"""Research search terms, folded exactly as the application's research search folds them (audit FA-D5-003 R1).

The application ranks judgments by the terms of their title and citations (services/d5-1/researchTerms.ts,
``researchTermsOf``). At 195,000 judgments it cannot fold every title per request, so the corpus stores each
text's terms, pre-folded, in the research term index (postgres/ddl/006_research_terms.sql); this module computes
them for the publication path (scraper/publication/research_index.py). Spec:
docs/superpowers/specs/2026-10-24-fa-d5-003-research-corpus-reader-design.md §7, rulings R20-R23.

The fold restates the TypeScript one step by step:

* the citation gate's character fold (services/d4-2/citationFold.ts ``foldDraftText``, its default reading):
  each code point is NFKD-decomposed; marks, format characters, default-ignorables and controls other than a
  newline are dropped; every decimal digit becomes its ASCII digit (its offset in its run of digits, mod 10);
  every dash and U+2212 becomes "-"; every blank becomes " "; then HTML comments, tags, character references and
  Markdown emphasis are removed, pass after pass, on the UTF-16 text (the TypeScript regex counts code units); a
  hyphenated line break between letters is joined;
* then the search's own steps: lower-case, runs of letters and numbers, stop words dropped, a lone letter dropped
  (a lone digit kept), lengths counted in UTF-16 code units.

Equality is the property the index needs (a different term set changes a document frequency or loses a
candidate), and it can only be claimed where both runtimes agree on Unicode: Node 22 ships Unicode 17, this
service's Python 3.12 ships 15.0. So the fold works only inside a declared DOMAIN of code points, each assigned in
both and closed under NFKD and lower-casing; a text with any other code point (in the input, an NFKD output or a
decoded character reference) returns None, and its row stays pending: the application then folds it itself at
query time, so the search stays exact. tests/fixtures/corpus/research-terms-golden.json, generated by the
TypeScript function only, pins this module to it: explicit cases, and one SHA-256 per 256-code-point block over
every DOMAIN code point in five contexts (corpus_service/tests/test_research_terms.py).
"""

