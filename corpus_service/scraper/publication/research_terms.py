_DOMAIN_STARTS: Final = [a for a, _ in DOMAIN]

#: Default_Ignorable_Code_Point (DerivedCoreProperties.txt) within the DOMAIN. unicodedata has no such property.
_DEFAULT_IGNORABLE: Final[Tuple[Tuple[int, int], ...]] = (
    (0x00AD, 0x00AD), (0x034F, 0x034F), (0x061C, 0x061C), (0x115F, 0x1160), (0x200B, 0x200F), (0x202A, 0x202E),
    (0x2060, 0x206F), (0x3164, 0x3164), (0xFE00, 0xFE0F), (0xFEFF, 0xFEFF), (0xFFA0, 0xFFA0), (0xFFF0, 0xFFF8),
    (0xE0000, 0xE0FFF),
)

#: citationFold.ts BLANKS: blank-rendering code points that separate words (some are default-ignorable).
_BLANKS: Final[FrozenSet[int]] = frozenset({0x2800, 0x3164, 0x115F, 0x1160, 0xFFA0, 0x0009})

#: citationFold.ts MARKUP (the default reading), matched on UTF-16 code units: Python's ``\Z`` is JavaScript's
#: ``$`` without the m flag.
_MARKUP: Final = re.compile(
    r"<!--[\s\S]*?(?:-->|\Z)|<[A-Za-z!/?][^>]{0,79}>|&[#A-Za-z0-9 -]{1,14};|&#[0-9]{1,7}(?![0-9])"
    r"|&#[xX][0-9A-Fa-f]{1,6}(?![0-9A-Fa-f])|&(?:nbsp|amp|lt|gt|quot|shy)|[*_`~]"
)
_ENTITY_STRIP: Final = re.compile(r"[\s-]")

#: citationFold.ts NAMED_ENTITIES.
_NAMED_ENTITIES: Final[Dict[str, str]] = {
    "nbsp": " ", "amp": "&", "lt": "<", "gt": ">", "quot": '"', "apos": "'", "ndash": "–", "mdash": "—",
    "shy": "­", "zwsp": "​", "zwj": "‍", "zwnj": "‌",
}


class _Unfoldable(Exception):
    """A code point outside the DOMAIN: the text is folded by the application at query time instead."""


def in_domain(cp: int) -> bool:
    i = bisect.bisect_right(_DOMAIN_STARTS, cp) - 1
    return i >= 0 and DOMAIN[i][0] <= cp <= DOMAIN[i][1]


def _ranges_hold(ranges: Sequence[Tuple[int, int]], cp: int) -> bool:
    return any(a <= cp <= b for a, b in ranges)


def _category(ch: str) -> str:
    return unicodedata.category(ch)


def _is_space(ch: str) -> bool:
    return _category(ch) in ("Zs", "Zl", "Zp")


def _is_nd(ch: str) -> bool:
    return _category(ch) == "Nd"


def _is_letter(ch: str) -> bool:
    return _category(ch)[0] == "L"


def _is_letter_or_number(ch: str) -> bool:
    return _category(ch)[0] in "LN"


_ASCII_DIGIT: Dict[int, str] = {}


def _ascii_digit(cp: int) -> str:
    """citationFold.ts asciiDigit: the offset of a decimal digit in its contiguous run of digits, mod 10."""
    cached = _ASCII_DIGIT.get(cp)
    if cached is None:
        start = cp
        while start > 0 and _is_nd(chr(start - 1)):
            start -= 1
        cached = str((cp - start) % 10)
        _ASCII_DIGIT[cp] = cached
    return cached


_PLANS: Dict[str, Tuple[str, ...]] = {}


def _plan(original: str) -> Tuple[str, ...]:
    """citationFold.ts planFor (and its ASCII fast path, which agrees with it): what one code point folds to."""
    plan = _PLANS.get(original)
    if plan is not None:
        return plan
    ocp = ord(original)
    if not in_domain(ocp):
        raise _Unfoldable()
    out: List[str] = []
    if original != " " and (ocp in _BLANKS or _is_space(original)):
        out.append(" ")
    else:
        for ch in unicodedata.normalize("NFKD", original):
            cp = ord(ch)
            if not in_domain(cp):
                raise _Unfoldable()
            if ch in ("\n", "\r"):
                if ch == "\n":
                    out.append("\n")
                continue
            if cp in _BLANKS or _is_space(ch):
                out.append(" ")
                continue
            category = _category(ch)
            if category[0] == "M" or category in ("Cf", "Cc") or _ranges_hold(_DEFAULT_IGNORABLE, cp):
                continue
            if category == "Nd":
                out.append(ch if cp < 0x80 else _ascii_digit(cp))
                continue
            if cp == 0x2212 or category == "Pd":
                out.append("-")
                continue
            out.append(ch)
    plan = tuple(out)
    _PLANS[original] = plan
    return plan


def _fold_chars(out: List[str], segment: str) -> None:
    for original in segment:
        out.extend(_plan(original))


def _parse_int(digits: str, radix: int) -> Optional[int]:
    """JavaScript ``parseInt(digits, radix)`` for the characters a character reference may hold; None for NaN."""
    if radix == 16 and digits[:2].lower() == "0x":
        digits = digits[2:]
    alphabet = "0123456789abcdef"[:radix]
    value = 0
    seen = False
    for ch in digits.lower():
        d = alphabet.find(ch)
        if d < 0:
            break
        value = value * radix + d
        seen = True
    return value if seen else None


def _decode_entity(entity: str) -> str:
    """citationFold.ts decodeEntity, after the caller removed blanks and hyphens."""
    body = entity[1:-1] if entity.endswith(";") else entity[1:]
    if body.startswith("#x") or body.startswith("#X"):
        cp = _parse_int(body[2:], 16)
    elif body.startswith("#"):
        cp = _parse_int(body[1:], 10)
    else:
        return _NAMED_ENTITIES.get(body.lower(), " ")
    if cp is None or cp > 0x10FFFF:
        return " "
    if not in_domain(cp):
        raise _Unfoldable()
    return chr(cp)


def _utf16(chars: Sequence[str]) -> Tuple[str, List[int]]:
    """The text as UTF-16 code units (one Python character per unit) and, per unit, the index of its character."""
    units: List[str] = []
    index: List[int] = []
    for i, ch in enumerate(chars):
        cp = ord(ch)
        if cp > 0xFFFF:
            v = cp - 0x10000
            units.append(chr(0xD800 + (v >> 10)))
            units.append(chr(0xDC00 + (v & 0x3FF)))
            index.extend((i, i))
        else:
            units.append(ch)
            index.append(i)
    return "".join(units), index


def _strip_markup_once(chars: List[str]) -> Optional[List[str]]:
    """citationFold.ts stripMarkupOnce (without the taint, which the search does not read); None when nothing matched."""
    text, index = _utf16(chars)
    if _MARKUP.search(text) is None:
        return None
    out: List[str] = []
    last = 0
    for m in _MARKUP.finditer(text):
        at = index[m.start()]
        end = index[m.end() - 1]
        out.extend(chars[last:at])
        token = m.group(0)
        if token.startswith("&"):
            decoded = _decode_entity(_ENTITY_STRIP.sub("", token))
            if decoded == " ":
                out.append(" ")
            else:
                _fold_chars(out, decoded)
        elif token.startswith("<"):
            out.append(" ")
        last = end + 1
    out.extend(chars[last:])
    return out


def _join_hyphenation(out: Sequence[str]) -> str:
    """citationFold.ts joinHyphenation: "SC-\\nMR" becomes "SCMR" (a hyphen after a letter, a line break, a letter)."""
    text: List[str] = []
    i = 0
    n = len(out)
    while i < n:
        if out[i] == "-" and i > 0 and _is_letter(out[i - 1]):
            j = i + 1
            while j < n and out[j] == " ":
                j += 1
            if j < n and out[j] == "\n":
                j += 1
                while j < n and out[j] == " ":
                    j += 1
                if j < n and _is_letter(out[j]):
                    i = j
                    continue
        text.append(out[i])
        i += 1
    return "".join(text)


def _utf16_length(term: str) -> int:
    return sum(2 if ord(ch) > 0xFFFF else 1 for ch in term)


def fold(text: str) -> Optional[str]:
    """``normaliseDraftText(text)`` (the default reading), or None outside the DOMAIN."""
    try:
        chars: List[str] = []
        _fold_chars(chars, text)
        for _ in range(64):
            stripped = _strip_markup_once(chars)
            if stripped is None:
                break
            chars = stripped
        return _join_hyphenation(chars)
    except _Unfoldable:
        return None


def research_terms_of(text: Optional[str]) -> Optional[List[str]]:
    """``researchTermsOf(text)``: the search terms in order, repeats kept; None when the text cannot be folded exactly
    here (a code point outside the DOMAIN): the row then stays pending and the application folds it itself."""
    if text is None:
        return []
    folded = fold(text)
    if folded is None:
        return None
    lowered = folded.lower()
    if any(not in_domain(ord(ch)) for ch in lowered):
        return None
    terms: List[str] = []
    run: List[str] = []
    for ch in lowered + " ":
        if _is_letter_or_number(ch):
            run.append(ch)
            continue
        if run:
            term = "".join(run)
            run = []
            if term in STOP_WORDS:
                continue
            # A lone letter ("s" of "s. 302") is noise; a lone digit is not ("PLD 2099 SC 1").
            if _utf16_length(term) < 2 and not (len(term) == 1 and _category(term)[0] == "N"):
                continue
            terms.append(term)
    return terms


def research_term_set(text: Optional[str]) -> Optional[FrozenSet[str]]:
    """The distinct terms of a text, as the index stores them; None as for ``research_terms_of``."""
    terms = research_terms_of(text)
    return None if terms is None else frozenset(terms)
