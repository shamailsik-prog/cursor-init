"""Audit FA-D5-003-R1-001 against real Postgres 16 + pgvector: the research term index (spec R20, R21).

postgres/ddl/006_research_terms.sql stores each title's and each citation's research terms, pre-folded, and each
judgment's size (its distinct terms over its title and promoted citations), and marks a row pending whenever what they
depend on is written, whoever writes it. The F19 publication indexes what it writes in its own
transaction; ``python -m scraper.publication.cli index-terms`` indexes the rest; a text the Python fold cannot reproduce
exactly stays pending (the application folds it at query time). The expected terms come from the golden
(tests/fixtures/corpus/research-terms-golden.json, generated by the TypeScript search) through
``research_terms.research_term_set``, which corpus_service/tests/test_research_terms.py pins to it.

Needs CORPUS_TEST_DATABASE_URL (see conftest.py); every test gets a fresh database. Synthetic data only (2099).
"""

import asyncio
import json
import sys
import uuid
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from scraper.publication.research_terms import research_term_set  # noqa: E402

PROVENANCE = {
    "source_name": "ri-curated-test",
    "source_url": "https://ri.example.invalid/judgment",
    "raw_storage_key": None,
    "fetched_at": "2099-01-02T03:04:05Z",
    "content_hash": "b" * 64,
    "extraction_method": "manual",
    "extractor_version": "ri-test-1",
}


def run(coro):
    return asyncio.run(coro)


async def _fetch(db, sql, params):
    from sqlalchemy import text

    engine = db.engine_for(db.url)
    try:
        async with engine.connect() as conn:
            return (await conn.execute(text(sql), params)).all()
    finally:
        await engine.dispose()


def fetch(db, sql, **params):
    return run(_fetch(db, sql, params))


def prepare(db):
    db.apply_annex_a()
    proc = db.migrate()
    assert proc.returncode == 0, f"scraper.migrate failed:\n{proc.stdout}\n{proc.stderr[-4000:]}"


def judgment_item(item_key, title, citations):
    return {
        "kind": "judgment",
        "item_key": item_key,
        "trust": {"level": "trusted", "confidence": 0.9},
        "provenance": dict(PROVENANCE),
        "citations": [{"parts": {"reporter": r, "year": "2099", "page": str(p), "court": c, "series": None, "note": None}} for r, p, c in citations],
        "case_title": title,
        "bench_type": "D.B.",
        "full_text": f"synthetic research index fixture {item_key}",
    }


def publish(doc):
    from scraper import database
    from scraper.publication.annex_a import publish_batch
    from scraper.publication.batch import parse_batch_json

    async def _run():
        async with database.engine.begin() as conn:
            return await publish_batch(conn, parse_batch_json(json.dumps(doc).encode("utf-8")), "ri-test-actor")

    return run(_run())


def title_terms(db, judgment_id):
    return {r[0] for r in fetch(db, "SELECT term FROM research_title_term WHERE judgment_id = CAST(:id AS uuid)", id=str(judgment_id))}


def citation_terms(db, citation_text):
    return {r[0] for r in fetch(db, "SELECT term FROM research_citation_term WHERE citation_text = :t", t=citation_text)}


def pending(db):
    titles = {str(r[0]) for r in fetch(db, "SELECT judgment_id FROM research_title_pending")}
    citations = {r[0] for r in fetch(db, "SELECT citation_text FROM research_citation_pending")}
    return titles, citations


def size(db, judgment_id):
    rows = fetch(db, "SELECT size FROM research_size WHERE judgment_id = CAST(:id AS uuid)", id=str(judgment_id))
    return rows[0][0] if rows else None


def expected_size(db, judgment_id, title):
    """The size the application computes: the union of the title's terms and each promoted citation's terms."""
    terms = set(research_term_set(title))
    for (text_,) in fetch(db, "SELECT citation_text FROM citation WHERE judgment_id = CAST(:id AS uuid) AND review_status = 'promoted'",
                          id=str(judgment_id)):
        terms |= set(research_term_set(text_))
    return len(terms)


def sql_text(value):
    return "'" + value.replace("'", "''") + "'"


def superuser_judgment(db, title, citation):
    """A visible judgment and citation written outside any publication (the superuser, as a bulk load would)."""
    pub, src, jid = uuid.uuid4(), uuid.uuid4(), uuid.uuid4()
    db.admin(
        "INSERT INTO corpus_publication (id, batch_key, input_sha256, source_kind, actor_id, publisher_session_user, "
        "item_count, promoted_count, quarantined_count, updated_count, unchanged_count, rejected_count, finished_at) "
        f"VALUES ('{pub}', 'curated/ri-{pub.hex[:8]}', '{'c' * 64}', 'curated', 'ri-test', current_user, 0, 0, 0, 0, 0, 0, now())",
        "INSERT INTO source_provenance (id, source_name, source_url, fetched_at, content_hash, extraction_method) "
        f"VALUES ('{src}', 'ri-test', 'https://ri.example.invalid/x', '2099-01-01Z', '{'d' * 64}', 'manual')",
        "INSERT INTO judgment (id, case_title, bench_type, classification, source_id, review_status, publication_id) "
        f"VALUES ('{jid}', {sql_text(title)}, 'division', 'public', '{src}', 'promoted', '{pub}')",
        "INSERT INTO citation (judgment_id, citation_text, source_id, review_status, publication_id) "
        f"VALUES ('{jid}', {sql_text(citation)}, '{src}', 'promoted', '{pub}')",
    )
    return jid


def test_a_publication_indexes_what_it_writes_and_clears_its_marks(corpus_db):
    prepare(corpus_db)
    writer, writer_pw = corpus_db.writer_role()
    titles = {"j1": "Bail after arrest under section 497 CrPC", "j2": "Muḥammad v. The State: ضمانت قبل از گرفتاری"}
    doc = {
        "format": "corpus-publication-batch/1",
        "batch_key": "curated/ri-publish",
        "source_kind": "curated",
        "items": [
            judgment_item("j1", titles["j1"], [("PLD", 41, "Karachi"), ("SCMR", 42, None)]),
            judgment_item("j2", titles["j2"], [("SCMR", 43, None)]),
        ],
    }
    with corpus_db.app_engine_as(writer, writer_pw):
        result = publish(doc)
    ids = {o.item_key: o.entity_id for o in result.outcomes if o.entity_type == "judgment"}
    assert set(ids) == {"j1", "j2"}
    for key, jid in ids.items():
        assert title_terms(corpus_db, jid) == set(research_term_set(titles[key])), key
    texts = [r[0] for r in fetch(corpus_db, "SELECT citation_text FROM citation ORDER BY 1")]
    assert len(texts) == 3
    for t in texts:
        assert citation_terms(corpus_db, t) == set(research_term_set(t)), t
    for key, jid in ids.items():
        assert size(corpus_db, jid) == expected_size(corpus_db, jid, titles[key]) > 0, key
    assert pending(corpus_db) == (set(), set())
    # The same batch again is a no-op: no write, no mark, the terms unchanged.
    with corpus_db.app_engine_as(writer, writer_pw):
        assert publish(doc).already is True
    assert pending(corpus_db) == (set(), set())


def test_index_terms_indexes_the_backlog_and_leaves_an_unfoldable_text_pending(corpus_db):
    prepare(corpus_db)
    writer, writer_pw = corpus_db.writer_role()
    plain = superuser_judgment(corpus_db, "Khula decree with dower returned", "2099 CLC 9101")
    unfoldable = superuser_judgment(corpus_db, "Bail 保释 arrest", "2099 CLC 9102")
    # Written outside a publication: pending, both titles and both citations.
    assert pending(corpus_db) == ({str(plain), str(unfoldable)}, {"2099 CLC 9101", "2099 CLC 9102"})
    proc = corpus_db.run_cli("index-terms", user=writer, password=writer_pw)
    assert proc.returncode == 0, proc.stderr[-2000:]
    assert json.loads(proc.stdout) == {"titles": 1, "citations": 2, "unindexable": 1, "pending_titles": 1, "pending_citations": 0}
    assert title_terms(corpus_db, plain) == {"khula", "decree", "dower", "returned"}
    assert citation_terms(corpus_db, "2099 CLC 9101") == {"2099", "clc", "9101"}
    assert title_terms(corpus_db, unfoldable) == set()
    assert pending(corpus_db) == ({str(unfoldable)}, set())
    # A re-run indexes nothing new and still leaves the unfoldable title to the application.
    again = corpus_db.run_cli("index-terms", user=writer, password=writer_pw)
    assert json.loads(again.stdout) == {"titles": 0, "citations": 0, "unindexable": 1, "pending_titles": 1, "pending_citations": 0}


def test_a_retitled_judgment_is_pending_again_and_reindexed(corpus_db):
    prepare(corpus_db)
    writer, writer_pw = corpus_db.writer_role()
    jid = superuser_judgment(corpus_db, "Rent ejectment of a tenant", "2099 CLC 9201")
    assert corpus_db.run_cli("index-terms", user=writer, password=writer_pw).returncode == 0
    assert title_terms(corpus_db, jid) == {"rent", "ejectment", "tenant"}
    corpus_db.admin(f"UPDATE judgment SET case_title = 'Pre-emption talb ishhad' WHERE id = '{jid}'")
    assert pending(corpus_db)[0] == {str(jid)}
    assert corpus_db.run_cli("index-terms", user=writer, password=writer_pw).returncode == 0
    assert title_terms(corpus_db, jid) == {"pre", "emption", "talb", "ishhad"}
    # A write that leaves the title alone (here a classification raise) does not mark it.
    corpus_db.admin(f"UPDATE judgment SET classification = 'internal' WHERE id = '{jid}'")
    assert pending(corpus_db) == (set(), set())


def test_index_terms_refuses_a_superuser_and_a_login_that_is_not_a_writer(corpus_db):
    prepare(corpus_db)
    outsider, outsider_pw = corpus_db.create_role("ri_out")
    proc = corpus_db.run_cli("index-terms", user=outsider, password=outsider_pw)
    assert proc.returncode == 4 and "not_corpus_writer" in proc.stderr
    admin = corpus_db._admin
    proc = corpus_db.run_cli("index-terms", user=admin.username, password=admin.password or "")
    assert proc.returncode == 4 and "superuser_session" in proc.stderr


def test_a_citation_write_marks_its_judgments_and_the_index_writes_their_sizes_again(corpus_db):
    prepare(corpus_db)
    writer, writer_pw = corpus_db.writer_role()
    title_a, title_b = "Rent ejectment of a tenant", "Khula decree with dower returned"
    a = superuser_judgment(corpus_db, title_a, "2099 CLC 9401")
    b = superuser_judgment(corpus_db, title_b, "2099 CLC 9402")

    def index_and_check():
        proc = corpus_db.run_cli("index-terms", user=writer, password=writer_pw)
        assert proc.returncode == 0, proc.stderr[-2000:]
        assert pending(corpus_db) == (set(), set())
        assert size(corpus_db, a) == expected_size(corpus_db, a, title_a)
        assert size(corpus_db, b) == expected_size(corpus_db, b, title_b)

    index_and_check()
    assert size(corpus_db, a) == 6  # rent, ejectment, tenant, 2099, clc, 9401
    # Quarantined: its terms leave the judgment's size.
    corpus_db.admin("UPDATE citation SET review_status = 'quarantined' WHERE citation_text = '2099 CLC 9401'")
    assert pending(corpus_db) == ({str(a)}, set())
    index_and_check()
    assert size(corpus_db, a) == 3
    # A new citation of a: its text and a are pending.
    corpus_db.admin(f"INSERT INTO citation (judgment_id, citation_text, source_id, review_status, publication_id) "
                    f"SELECT judgment_id, '2099 SCMR 9403', source_id, 'promoted', publication_id FROM citation WHERE citation_text = '2099 CLC 9402'",
                    f"UPDATE citation SET judgment_id = '{a}' WHERE citation_text = '2099 SCMR 9403'")
    assert pending(corpus_db) == ({str(a), str(b)}, {"2099 SCMR 9403"})
    index_and_check()
    assert size(corpus_db, a) == 6
    # Moved from b to a: both judgments are pending.
    corpus_db.admin(f"UPDATE citation SET judgment_id = '{a}' WHERE citation_text = '2099 CLC 9402'")
    assert pending(corpus_db) == ({str(a), str(b)}, set())
    index_and_check()
    assert (size(corpus_db, a), size(corpus_db, b)) == (8, 4)
    # Deleted: its judgment is pending; a write that changes none of text, judgment or status marks nothing.
    corpus_db.admin("DELETE FROM citation WHERE citation_text = '2099 SCMR 9403'")
    assert pending(corpus_db) == ({str(a)}, set())
    index_and_check()
    corpus_db.admin("UPDATE citation SET confidence = 0.75 WHERE citation_text = '2099 CLC 9402'")
    assert pending(corpus_db) == (set(), set())


def test_the_first_application_of_006_marks_every_existing_row_and_a_reapplication_does_not(corpus_db):
    corpus_db.apply_annex_a(("001_corpus_contract.sql", "003_corpus_publication.sql", "004_authority_read_views.sql", "005_research_reader.sql"))
    src, jid = uuid.UUID(int=1), uuid.UUID(int=2)
    corpus_db.admin(
        f"INSERT INTO source_provenance (id, source_name, fetched_at, content_hash, extraction_method) VALUES ('{src}', 'ri', '2099-01-01Z', '{'e' * 64}', 'manual')",
        f"INSERT INTO judgment (id, case_title, bench_type, source_id) VALUES ('{jid}', 'Before 006', 'single', '{src}')",
        f"INSERT INTO citation (judgment_id, citation_text, source_id) VALUES ('{jid}', '2099 CLC 9301', '{src}')",
    )
    corpus_db.apply_annex_a(("006_research_terms.sql",))
    assert pending(corpus_db) == ({str(jid)}, {"2099 CLC 9301"})
    # As if indexed: a size written and the marks cleared. A re-application then marks nothing ...
    corpus_db.admin(f"INSERT INTO research_size (judgment_id, size) VALUES ('{jid}', 4)",
                    "DELETE FROM research_title_pending", "DELETE FROM research_citation_pending")
    corpus_db.apply_annex_a(("006_research_terms.sql",))
    assert pending(corpus_db) == (set(), set())
    # ... but a judgment without a stored size is marked again, so the index always catches up.
    corpus_db.admin("DELETE FROM research_size")
    corpus_db.apply_annex_a(("006_research_terms.sql",))
    assert pending(corpus_db) == ({str(jid)}, set())
